"""Fetch the Times Gate font catalog and write it as Markdown (with samples).

The cloud endpoint ``Device/GetTimeDialFontList`` returns the device-scoped
font registry (the ``font`` ids usable in ``Draw/SendHttpItemList``), with
per-font name, glyph size, download URL and — crucially — the exact
``charset``. Note the endpoint has been flaky in the past: an empty
``FontList`` usually means the DeviceId/DeviceType params were omitted, but
retry later if it persists.

Font files are served from Divoom's CDN (``https://f.divoom-gz.com/`` +
``fontUrl``) but are stored in an encrypted/proprietary container (verified:
no TTF magic bytes), so local preview rendering is not possible. For visual
samples, use ``show_font_samples.py`` to display batches on the device and
photograph them. (The plain-TTF catalog on appchina's ``GetTimeDialFontV2``
is the *Frame* family's separate registry — same ids, different fonts — and
does NOT apply to the Times Gate.)

Usage:
    python get_font_list.py [DEVICE_ID] [OUTPUT_DIR]

DEVICE_ID defaults to 0 (the catalog appears to be shared, but pass your own
id — from discovery / the Divoom app — to be safe). OUTPUT_DIR defaults to
the repo's docs/ directory; writes docs/FONTS_CATALOG.md.
"""
from __future__ import annotations

import json
import os
import re
import sys
import urllib.request

URL = "https://app.divoom-gz.com/Device/GetTimeDialFontList"
CDN = "https://f.divoom-gz.com/"

TYPE_LABELS = {0: "bitmap", 1: "vector", 3: "image glyph"}

# Style hints derived from the font *name* (the files are encrypted, so this
# is the best available signal). Keyword → hint.
_STYLE_HINTS = [
    (("segment",), "7-segment/digital"),
    (("pixel", "8-bit", "8bit"), "pixel/8-bit"),
    (("serif", "宋体"), "serif"),
    (("圆", "round", "rounded"), "rounded"),
    (("hand", "手写", "script"), "handwriting"),
    (("bold", "粗"), "bold"),
]


def style_hint(name: str) -> str:
    low = name.lower()
    return ", ".join(h for keys, h in _STYLE_HINTS if any(k in low for k in keys))


def categories(charset: str, ftype: int) -> list[str]:
    """Functional buckets a font belongs to, from its (API) charset."""
    if not charset:
        # The classic bitmap "standard fonts" render general text.
        return ["full-text"] if ftype == 0 else ["unknown-charset"]
    cs = set(charset)
    has_digits = any(c.isdigit() for c in cs)
    lower = sum(c.islower() for c in cs)
    upper = sum(c.isupper() for c in cs)
    cats = []
    if lower >= 20 and upper >= 20 and len(cs & set("%.:-/")) >= 3:
        cats.append("full-text")
    elif lower >= 20 and upper >= 20:
        cats.append("letters-digits")
    elif upper >= 20:
        cats.append("caps-digits")
    if has_digits:
        if "%" in cs:
            cats.append("percent")
        if "." in cs:
            cats.append("decimals")
        if ":" in cs:
            cats.append("clock")
        if "$" in cs:
            cats.append("currency")
        if "c" in cs and "f" in cs and lower <= 4:
            cats.append("temperature")
        if cs <= set("0123456789"):
            cats.append("digits-only")
    return cats or ["other"]

_PREFERRED_SAMPLE = "Ab12.5%:-$"


def main() -> int:
    args = list(sys.argv[1:])
    device_id = int(args[0]) if args else 0
    out_dir = args[1] if len(args) > 1 else os.path.join(
        os.path.dirname(__file__), "..", "docs"
    )

    body = json.dumps({"DeviceId": device_id, "DeviceType": "LCD"}).encode()
    req = urllib.request.Request(URL, body, {"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=15) as resp:  # noqa: S310 - fixed Divoom host
        data = json.loads(resp.read())
    fonts = data.get("FontList", [])
    if not fonts:
        print("Empty FontList — endpoint flaky or params rejected; try again later.")
        return 1

    lines = [
        "# Times Gate font catalog (`Draw/SendHttpItemList` font ids)",
        "",
        f"Generated by `scripts/get_font_list.py` from `{URL}`",
        f"({len(fonts)} fonts). The `charset` column is authoritative: glyphs",
        "outside it are silently dropped by the device. Hand-verified test",
        "notes and photographed samples live in FONTS.md.",
        "",
        "Font files © Divoom (and their respective type foundries), served",
        f"from Divoom's CDN (`{CDN}` + the catalog's `fontUrl`). Note: the",
        "files are stored in an encrypted/proprietary container — they are",
        "NOT directly usable TTFs, so no local previews can be rendered.",
        "Use `scripts/show_font_samples.py` to display fonts on the device",
        "and photograph them instead.",
        "",
    ]

    # --- "pick a working font fast" section: functional lists ---------------
    CAT_LABELS = {
        "full-text": "Full text (upper+lower case, digits, symbols) — labels, any value",
        "letters-digits": "Letters + digits (few/no symbols) — unit text like `kWh`",
        "caps-digits": "UPPERCASE + digits — compact unit text like `W`, `KM`",
        "percent": "Digits with `%` — percentages",
        "decimals": "Digits with `.` — decimal values",
        "clock": "Digits with `:` — times/clocks",
        "currency": "Digits with `$` — currency",
        "temperature": "Digits with `c`/`f` — temperatures (`21c`)",
        "digits-only": "Bare digits only — integers",
        "unknown-charset": "Charset not published (try on device)",
        "other": "Other",
    }
    def height(f: dict) -> int:
        try:
            return int(f.get("high", 0))
        except (TypeError, ValueError):
            return 0

    def family_name(f: dict) -> str:
        """Font name with the leading size token stripped (e.g. '10pt standard
        font' / '7*9 numerals' -> 'standard font' / 'numerals'), so the same
        family at different sizes shares a name."""
        n = str(f.get("name", ""))
        n = re.sub(r"^\s*\d+\s*[x*×]\s*\d+\s*", "", n)  # '7*9 ', '18×22 '
        n = re.sub(r"\d+\s*pt\b", "", n)                # '10pt '
        return n.strip() or "unnamed"

    def sizes_str(members: list[dict]) -> str:
        """Ids of a family, sorted by height. Caps very large families to a
        small/card/large spread so the overview stays readable."""
        by_h = sorted(members, key=height)
        if len(by_h) > 6:
            keep = [by_h[0]]  # smallest
            card = next((f for f in by_h if 12 <= height(f) <= 16), None)
            if card and card not in keep:
                keep.append(card)
            keep.append(by_h[-1])  # largest
            extra = len(by_h) - len(keep)
            tail = f" (+{extra} more sizes)" if extra > 0 else ""
            return ", ".join(f"`{int(f['id'])}` ({height(f)}px)" for f in keep) + tail
        return ", ".join(f"`{int(f['id'])}` ({height(f)}px)" for f in by_h)

    def usefulness(members: list[dict]) -> tuple:
        cs = set(str(members[0].get("charset", "")))
        return (len(members), any(c.islower() for c in cs), len(cs))

    # Group each use-case's fonts into families (same charset + same name
    # sans size = same font at different sizes).
    lines += [
        "## Quick picks by use case",
        "",
        "Grouped by **font family** — fonts on one line are the same font at",
        "different sizes, so pick the `id` whose height fits (the card default",
        "is 14px). Glyphs outside a font's charset are dropped silently.",
        "",
    ]
    for cat, label in CAT_LABELS.items():
        members = [
            f for f in fonts
            if cat in categories(str(f.get("charset", "")), int(f.get("type", -1)))
        ]
        if not members:
            continue
        families: dict[tuple, list[dict]] = {}
        for f in members:
            families.setdefault((family_name(f), str(f.get("charset", ""))), []).append(f)
        top = sorted(families.items(), key=lambda kv: usefulness(kv[1]), reverse=True)[:4]
        lines.append(f"- **{label}**:")
        for (fam, _cs), fam_members in top:
            lines.append(f"    - _{fam}_: {sizes_str(fam_members)}")

    # --- full catalog: the raw endpoint data, one row per font --------------
    lines += [
        "",
        "## Full catalog (raw)",
        "",
        "Every font id as returned by the endpoint. The `charset` is",
        "authoritative; `style hint` is guessed from the name.",
        "",
        "| id | size | type | name | style hint | charset | file |",
        "|---|---|---|---|---|---|---|",
    ]
    for f in sorted(fonts, key=lambda f: int(f["id"])):
        fid = int(f["id"])
        charset = str(f.get("charset", "")).replace("|", "\\|")
        cell_charset = charset[:60] + ("…" if len(charset) > 60 else "")
        file_url = f.get("fontUrl") or f.get("url") or ""
        file_cell = f"[file]({CDN}{file_url})" if file_url else "—"
        name = str(f.get("name", "?")).replace("|", "\\|")
        size = f"{f.get('width', '?')}×{f.get('high', '?')}"
        ftype = TYPE_LABELS.get(int(f.get("type", -1)), f.get("type"))
        hint = style_hint(name) or "—"
        lines.append(
            f"| {fid} | {size} | {ftype} | {name} | {hint} "
            f"| `{cell_charset}` | {file_cell} |"
        )

    path = os.path.join(out_dir, "FONTS_CATALOG.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {path} ({len(fonts)} fonts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
